export const GLYPHS = { big: BIG, tiny: TINY };
const parse = (set) => Object.fromEntries(Object.entries(set).map(([k, v]) => [k, v.split(',')]));
const FONTS = { big: { g: parse(BIG), h: 7 }, tiny: { g: parse(TINY), h: 5 } };
const cache = new Map();

const norm = (s) => String(s).toUpperCase().normalize('NFD').replace(/[̀-ͯ]/g, '');

export function textWidth(str, font = 'big', scale = 1) {
  const F = FONTS[font];
  let w = 0;
  for (const ch of norm(str)) w += ((F.g[ch] ?? F.g['?'])[0].length + 1);
  return Math.max(0, w - 1) * scale;
}

function bake(str, font, color, scale, shadow) {
  const F = FONTS[font], s = norm(str);
  const w = textWidth(s, font, 1), h = F.h;
  const pad = shadow ? 1 : 0;
  const c = typeof OffscreenCanvas !== 'undefined' ? new OffscreenCanvas(Math.max(1, (w + pad) * scale), (h + pad) * scale) : Object.assign(document.createElement('canvas'), { width: Math.max(1, (w + pad) * scale), height: (h + pad) * scale });
  const x = c.getContext('2d');
  const pass = (col, ox, oy) => {
    x.fillStyle = col;
    let cx = 0;
    for (const ch of s) {
      const g = F.g[ch] ?? F.g['?'];
      for (let r = 0; r < g.length; r++) for (let k = 0; k < g[r].length; k++) if (g[r][k] === '1') x.fillRect((cx + k + ox) * scale, (r + oy) * scale, scale, scale);
      cx += g[0].length + 1;
    }
  };
  if (shadow) pass(shadow, 1, 1);
  pass(color, 0, 0);
  return { c, w: w * scale, h: h * scale };
}

/**
 * Draw text. align: 'left' | 'center' | 'right'. Returns the width in pixels.
 * opts: { font: 'big'|'tiny', color, scale, align, shadow: css colour or null }
 */
export function text(ctx, str, x, y, { font = 'big', color = '#fff', scale = 1, align = 'left', shadow = null } = {}) {
  if (str == null || str === '') return 0;
  const key = `${font}|${color}|${scale}|${shadow}|${str}`;
  let b = cache.get(key);
  if (!b) {
    if (cache.size > 600) cache.clear();
    b = bake(str, font, color, scale, shadow);
    cache.set(key, b);
  }
  const dx = align === 'center' ? -(b.w >> 1) : align === 'right' ? -b.w : 0;
  ctx.drawImage(b.c, Math.round(x) + dx, Math.round(y));
  return b.w;
}
